// Generates src/ui/icons.generated.ts from @material-symbols/svg-400 (rounded), so only the icons
// the app uses are bundled (spec 002 research §7). Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const HABIT_ICONS = ["wb_sunny", "menu_book", "auto_stories", "bedtime", "nightlight", "family_restroom", "self_improvement",
  "directions_walk", "fitness_center", "water_drop", "restaurant", "no_food", "block", "favorite", "volunteer_activism",
  "psychology", "spa", "edit_note", "school", "work", "phone_disabled", "mosque", "eco", "schedule"];
const APP_ICONS = ["repeat", "videocam", "location_on", "delete", "check_box", "star", "bar_chart", "groups", "more_horiz", "add", "close", "settings", "keyboard_arrow_down",
  "keyboard_arrow_up", "check", "check_circle", "format_quote", "autorenew", "north_east", "chevron_left", "local_fire_department",
  "event", "edit", "flag", "bolt", "palette", "visibility", "visibility_off", "today", "local_florist"];
// «أثرك»، «المجتمع»، «المزيد» (src/ui/theme/screens.css).
const SCREEN_ICONS = ["person", "calendar_month", "trending_up", "arrow_back", "chevron_right", "notifications", "diamond",
  "south", "space_dashboard", "description", "play_arrow", "logout", "group", "map", "rate_review", "account_circle", "inventory_2"];
// The designs draw habit and navigation icons at weight 200. Those outlines are checked in under
// scripts/icons-thin/ (instanced at wght 200 from the Material Symbols Rounded variable font the
// designs embed; Apache-2.0), so no second icon package is needed.
const NAV_THIN = ["check_box", "star", "bar_chart", "groups", "more_horiz"];
// «خطتي» and the habit flow only: their own module, so «يومك» does not ship them.
const FLOW_ICONS = ["notifications", "speed", "group", "lock", "remove", "reorder"];
// Sign-in, sign-up and «رحلة البداية» only: their own module, so member screens do not ship them.
const AUTH_ICONS = ["mail", "call", "key", "mark_email_read", "badge", "lock"];
// Time-of-day cards in the habit flow draw these at weight 200 too (the other three are habit icons).
const TIME_THIN = ["wb_twilight"];

// Raw markup (not URL-encoded): IonIcon parses `;utf8,<svg…>` data URLs with DOMParser, as ionicons/icons does.
const toDataUrl = (svg) => `data:image/svg+xml;utf8,${svg.replace(/\s+/g, " ").replace(/"/g, "'").trim()}`;
const read = (name) => readFileSync(new URL(`../node_modules/@material-symbols/svg-400/rounded/${name}.svg`, import.meta.url), "utf8");

const readThin = (name) => readFileSync(new URL(`./icons-thin/${name}.svg`, import.meta.url), "utf8");
const entries = [...new Set([...HABIT_ICONS, ...APP_ICONS, ...SCREEN_ICONS])].map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(toDataUrl(read(n)))},`);
const thin = (names) => names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(toDataUrl(readThin(n)))},`).join("\n");
writeFileSync(
  new URL("../src/ui/icons.generated.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs — do not edit. Material Symbols Rounded (Apache-2.0).\n` +
    `export const HABIT_ICON_NAMES = ${JSON.stringify(HABIT_ICONS)} as const;\n` +
    `export const ICONS = {\n${entries.join("\n")}\n} as const;\n` +
    `/** Bottom navigation icons at weight 200. */\n` +
    `export const NAV_ICONS_THIN = {\n${thin(NAV_THIN)}\n} as const;\n`,
);
// Habit icons at weight 200 live in their own module so only the lazily loaded habit row ships them.
writeFileSync(
  new URL("../src/ui/icons-thin.generated.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs — do not edit. Material Symbols Rounded (Apache-2.0).\n` +
    `/** Habit icons at weight 200 (the designs' habit circles). */\n` +
    `export const HABIT_ICONS_THIN = {\n${thin(HABIT_ICONS)}\n} as const;\n` +
    `/** Extra weight-200 icons of the habit flow's time-of-day cards. */\n` +
    `export const TIME_ICONS_THIN = {\n${thin(TIME_THIN)}\n} as const;\n`,
);
writeFileSync(
  new URL("../src/ui/icons-flow.generated.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs — do not edit. Material Symbols Rounded (Apache-2.0).\n` +
    `/** Icons of «خطتي» and the habit flow (weight 400). */\n` +
    `export const FLOW_ICONS = {\n${FLOW_ICONS.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(toDataUrl(read(n)))},`).join("\n")}\n} as const;\n`,
);
writeFileSync(
  new URL("../src/ui/icons-auth.generated.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs — do not edit. Material Symbols Rounded (Apache-2.0).\n` +
    `/** Icons of sign-in, sign-up and «رحلة البداية» (weight 400). */\n` +
    `export const AUTH_ICONS = {\n${AUTH_ICONS.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(toDataUrl(read(n)))},`).join("\n")}\n} as const;\n`,
);
console.log(`icons: ${entries.length}`);
