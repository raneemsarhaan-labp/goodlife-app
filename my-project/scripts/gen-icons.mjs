// Generates src/ui/icons.generated.ts from @material-symbols/svg-400 (rounded), so only the icons
// the app uses are bundled (spec 002 research §7). Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const HABIT_ICONS = ["wb_sunny", "menu_book", "auto_stories", "bedtime", "nightlight", "family_restroom", "self_improvement",
  "directions_walk", "fitness_center", "water_drop", "restaurant", "no_food", "block", "favorite", "volunteer_activism",
  "psychology", "spa", "edit_note", "school", "work", "phone_disabled", "mosque", "eco", "schedule"];
const APP_ICONS = ["check_box", "star", "bar_chart", "groups", "more_horiz", "add", "close", "settings", "keyboard_arrow_down",
  "keyboard_arrow_up", "check", "check_circle", "format_quote", "autorenew", "north_east", "chevron_left", "local_fire_department",
  "event", "edit", "flag", "bolt", "palette", "visibility", "today"];

// Raw markup (not URL-encoded): IonIcon parses `;utf8,<svg…>` data URLs with DOMParser, as ionicons/icons does.
const toDataUrl = (svg) => `data:image/svg+xml;utf8,${svg.replace(/\s+/g, " ").replace(/"/g, "'").trim()}`;
const read = (name) => readFileSync(new URL(`../node_modules/@material-symbols/svg-400/rounded/${name}.svg`, import.meta.url), "utf8");

const entries = [...new Set([...HABIT_ICONS, ...APP_ICONS])].map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(toDataUrl(read(n)))},`);
writeFileSync(
  new URL("../src/ui/icons.generated.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs — do not edit. Material Symbols Rounded (Apache-2.0).\n` +
    `export const HABIT_ICON_NAMES = ${JSON.stringify(HABIT_ICONS)} as const;\n` +
    `export const ICONS = {\n${entries.join("\n")}\n} as const;\n`,
);
console.log(`icons: ${entries.length}`);
